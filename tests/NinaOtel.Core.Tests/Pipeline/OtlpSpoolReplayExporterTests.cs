public sealed class OtlpSpoolReplayExporterTests : IDisposable
{
    private readonly string root = Path.Combine(Path.GetTempPath(), "nina-otel-replay-otlp-tests", Guid.NewGuid().ToString("N"));

    [Fact]
    public async Task StartupReplay_SendsAlpha57SpoolThroughOtlpGrpcWithOriginalTimestamps()
    {
        // Generated by the actual alpha.57 DiskTelemetrySpool from synthetic records.
        Directory.CreateDirectory(root);
        File.Copy(Path.Combine(AppContext.BaseDirectory, "Fixtures", "alpha57-spool.ready.json"),
            Path.Combine(root, "0639359481301234567-abcd0123abcd0123abcd0123abcd0123.ready"));
        var spool = new DiskTelemetrySpool(root);
        using var receiver = new Receiver();
        using var replay = new OtlpSpoolReplayExporter(
            new OtlpOptions { Endpoint = new Uri("https://collector.example:4317/") },
            () => new HttpClient(receiver, disposeHandler: false));
        var exporter = new DurableTelemetryExporter(new NoLiveExport(), replay, spool);
        try
        {
            await DurableTelemetryExporterTests.UntilAsync(() => !spool.EnumerateReadyFiles().Any());
            Assert.Empty(Directory.GetFiles(root, "*.invalid"));
        }
        finally
        {
            exporter.Dispose();
            await exporter.ReplayCompletion;
        }

        var captured = new DateTimeOffset(2026, 11, 18, 11, 15, 30, TimeSpan.Zero).AddTicks(1234567);
        var metricsRequest = ExportMetricsServiceRequest.Parser.ParseFrom(receiver.Payload(
            "/opentelemetry.proto.collector.metrics.v1.MetricsService/Export"));
        var metrics = Assert.Single(Assert.Single(metricsRequest.ResourceMetrics).ScopeMetrics).Metrics;
        var points = metrics.Single(metric => metric.Name == "camera_sensor_temperature").Gauge.DataPoints;
        Assert.Equal([Nanos(captured), Nanos(captured.AddSeconds(10))], points.Select(point => point.TimeUnixNano));
        Assert.Equal([-9.75, -10.0], points.Select(point => point.AsDouble));
        Assert.All(points, point => Assert.Contains(point.Attributes,
            attr => attr.Key == "camera_name" && attr.Value.StringValue == "Fixture camera"));
        var legacy = Assert.Single(metrics.Single(metric => metric.Name == "phd2_guide_rms_ra_arcsec").Gauge.DataPoints);
        Assert.Equal(Nanos(captured.AddSeconds(11)), legacy.TimeUnixNano);
        Assert.Equal(0.45, legacy.AsDouble);

        var logsRequest = ExportLogsServiceRequest.Parser.ParseFrom(receiver.Payload(
            "/opentelemetry.proto.collector.logs.v1.LogsService/Export"));
        var logs = Assert.Single(Assert.Single(logsRequest.ResourceLogs).ScopeLogs).LogRecords;
        Assert.Equal(
            Enumerable.Range(12, 4).Select(offset => Nanos(captured.AddSeconds(offset))),
            logs.Select(log => log.TimeUnixNano));
        Assert.Equal("Fixture log message", logs[0].Body.StringValue);
        Assert.Equal(17, (int)logs[0].SeverityNumber);

        var tracesRequest = ExportTraceServiceRequest.Parser.ParseFrom(receiver.Payload(
            "/opentelemetry.proto.collector.trace.v1.TraceService/Export"));
        var span = Assert.Single(Assert.Single(Assert.Single(tracesRequest.ResourceSpans).ScopeSpans).Spans);
        Assert.Equal(Nanos(captured.AddSeconds(13)), span.StartTimeUnixNano);
        Assert.Equal(Nanos(captured.AddSeconds(15)), span.EndTimeUnixNano);
        Assert.Equal(Nanos(captured.AddSeconds(14)), Assert.Single(span.Events).TimeUnixNano);
        Assert.Equal(Convert.FromHexString("0123456789abcdef0123456789abcdef"), span.TraceId.ToByteArray());
    }

    [Fact]
    public async Task Replay_AfterRestart_PreservesStartAndEventFromPreviouslyDrainedBatch()
    {
        var spool = new DiskTelemetrySpool(root);
        using var receiver = new Receiver();
        var start = DateTimeOffset.UnixEpoch.AddDays(10).AddTicks(123);
        var stop = start.AddMinutes(1);
        await spool.AppendBatchAsync(
        [
            TelemetryRecord.Span(start, "test", "exposure", SpanEventKind.Start, "span-1", TelemetryPriority.Normal),
            TelemetryRecord.Span(start.AddSeconds(1), "test", "exposing", SpanEventKind.Event, "span-1", TelemetryPriority.Normal),
        ], CancellationToken.None);
        await DrainAsync();

        await spool.AppendBatchAsync(
        [
            TelemetryRecord.Span(stop, "test", "exposure", SpanEventKind.Stop, "span-1", TelemetryPriority.Normal),
        ], CancellationToken.None);
        await DrainAsync();

        var request = ExportTraceServiceRequest.Parser.ParseFrom(receiver.Payload(
            "/opentelemetry.proto.collector.trace.v1.TraceService/Export"));
        var span = Assert.Single(Assert.Single(Assert.Single(request.ResourceSpans).ScopeSpans).Spans);
        Assert.Equal(Nanos(start), span.StartTimeUnixNano);
        Assert.Equal(Nanos(stop), span.EndTimeUnixNano);
        Assert.Equal(Nanos(start.AddSeconds(1)), Assert.Single(span.Events).TimeUnixNano);

        async Task DrainAsync()
        {
            var exporter = new DurableTelemetryExporter(new NoLiveExport(), new OtlpSpoolReplayExporter(
                new OtlpOptions { Endpoint = new Uri("https://collector.example:4317") },
                () => new HttpClient(receiver, disposeHandler: false)), new DiskTelemetrySpool(root));
            try
            {
                await DurableTelemetryExporterTests.UntilAsync(() => !spool.EnumerateReadyFiles().Any());
                Assert.Empty(Directory.GetFiles(root, "*.invalid"));
            }
            finally
            {
                exporter.Dispose();
                await exporter.ReplayCompletion;
            }
        }
    }

    [Theory]
    [InlineData(OtlpProtocol.Grpc, 200, "3", true)]
    [InlineData(OtlpProtocol.Grpc, 200, "4", false)]
    [InlineData(OtlpProtocol.Grpc, 200, "14", false)]
    [InlineData(OtlpProtocol.HttpProtobuf, 400, null, true)]
    [InlineData(OtlpProtocol.HttpProtobuf, 503, null, false)]
    public async Task SendAsync_ClassifiesCollectorResponses(
        OtlpProtocol protocol, int status, string? grpcStatus, bool permanent)
    {
        using var receiver = new Receiver((HttpStatusCode)status, grpcStatus);
        using var transport = new OtlpDirectTransport(
            new OtlpOptions { Endpoint = new Uri("https://collector.example"), Protocol = protocol }, "metrics",
            () => new HttpClient(receiver, disposeHandler: false));
        var failure = await Assert.ThrowsAsync<TelemetryExportException>(() =>
            transport.SendAsync([1], CancellationToken.None));
        Assert.Equal(permanent, failure.IsPermanent);
    }

    public void Dispose()
    {
        if (Directory.Exists(root))
        {
            Directory.Delete(root, recursive: true);
        }
    }

    private static ulong Nanos(DateTimeOffset at) => checked((ulong)(at.UtcTicks - DateTimeOffset.UnixEpoch.Ticks) * 100);

    private sealed class NoLiveExport : ITelemetryExporter
    {
        public Task ExportAsync(IReadOnlyList<TelemetryRecord> records, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Expected startup to drain without a live export.");
    }

    private sealed class Receiver(HttpStatusCode status = HttpStatusCode.OK, string? grpcStatus = "0") : HttpMessageHandler
    {
        private readonly ConcurrentDictionary<string, byte[]> received = new();

        public byte[] Payload(string path)
        {
            var frame = received[path];
            Assert.Equal(0, frame[0]);
            Assert.Equal(frame.Length - 5, BinaryPrimitives.ReadInt32BigEndian(frame.AsSpan(1, 4)));
            return frame[5..];
        }

        protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken)
        {
            received[request.RequestUri!.AbsolutePath] = await request.Content!.ReadAsByteArrayAsync(cancellationToken);
            var response = new HttpResponseMessage(status);
            if (grpcStatus is not null)
            {
                response.TrailingHeaders.TryAddWithoutValidation("grpc-status", grpcStatus);
            }
            return response;
        }
    }
}
